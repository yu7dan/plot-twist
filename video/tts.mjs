// Voice-over: one MP3 per narration line (Microsoft neural voice), plus each line's duration and word timings.
// Writes out/vo/<id>.mp3 and design/demo/timings.js, which the demo's tour uses to pace itself to the voice.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { MsEdgeTTS, OUTPUT_FORMAT } from "msedge-tts";

const here = path.dirname(fileURLToPath(import.meta.url));
const N = JSON.parse(fs.readFileSync(path.join(here, "narration.json"), "utf8"));
const outDir = path.join(here, "out", "vo");
fs.mkdirSync(outDir, { recursive: true });

const duration = (file) =>
  Number(execFileSync("ffprobe", ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", file]).toString().trim());

/** One line → mp3 + word timings. The service sometimes drops a stream, so retry a few times. */
async function synth(text) {
  for (let attempt = 1; ; attempt++) {
    const dir = fs.mkdtempSync(path.join(outDir, "tmp-"));
    try {
      const tts = new MsEdgeTTS();
      await tts.setMetadata(N.voice, OUTPUT_FORMAT.AUDIO_24KHZ_96KBITRATE_MONO_MP3, { wordBoundaryEnabled: true });
      const { audioFilePath, metadataFilePath } = await tts.toFile(dir, text, { rate: N.rate });
      const audio = fs.readFileSync(audioFilePath);
      const meta = metadataFilePath && fs.existsSync(metadataFilePath) ? JSON.parse(fs.readFileSync(metadataFilePath, "utf8")) : [];
      tts.close?.();
      return { audio, meta };
    } catch (e) {
      if (attempt >= 4) throw e;
      console.log(`  retry ${attempt}: ${e.message.slice(0, 60)}`);
      await new Promise((r) => setTimeout(r, 1500 * attempt));
    } finally {
      fs.rmSync(dir, { recursive: true, force: true });
    }
  }
}

// Lines whose text didn't change since the last run are reused.
const cacheFile = path.join(outDir, "cache.json");
const cache = fs.existsSync(cacheFile) ? JSON.parse(fs.readFileSync(cacheFile, "utf8")) : {};
const timings = {};
for (const ch of N.chapters) {
  for (const line of ch.lines) {
    const mp3 = path.join(outDir, `${line.id}.mp3`);
    const key = `${N.voice}|${N.rate}|${line.en}`;
    if (cache[line.id]?.key === key && fs.existsSync(mp3)) {
      timings[line.id] = cache[line.id].timing;
      console.log(line.id, "cached");
      continue;
    }
    const { audio, meta } = await synth(line.en);
    fs.writeFileSync(mp3, audio);
    // Word boundaries arrive in 100-ns ticks.
    const words = [];
    for (const m of meta.Metadata ?? meta) {
      const d = m.Data ?? m;
      if ((m.Type ?? d.Type) === "WordBoundary") words.push({ w: String(d.text?.Text ?? d.text ?? "").toLowerCase(), t: (d.Offset ?? 0) / 1e7 });
    }
    timings[line.id] = { dur: Number(duration(mp3).toFixed(3)), words };
    cache[line.id] = { key, timing: timings[line.id] };
    fs.writeFileSync(cacheFile, JSON.stringify(cache));
    console.log(line.id, timings[line.id].dur.toFixed(2) + "s", words.length + " words");
  }
}

const total = Object.values(timings).reduce((s, t) => s + t.dur, 0);
console.log(`voice total ${total.toFixed(1)}s`);
fs.writeFileSync(
  path.join(here, "..", "design", "demo", "timings.js"),
  `// Generated by video/tts.mjs — voice-over line durations and word timings (seconds).\nwindow.VO = ${JSON.stringify({ lines: N.chapters.flatMap((c) => c.lines.map((l) => ({ ...l, ch: c.id }))), timings })};\n`,
);
process.exit(0);
